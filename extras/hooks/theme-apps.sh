#!/bin/bash

# Omarchy theme-set hook: themes Zen Browser and IntelliJ IDEA from the current
# theme's colors.toml. Omarchy itself only themes Chromium-family browsers and
# VS Code, so these two need their own generated configs.
#
# Install: omarchy hook install theme-set extras/hooks/theme-apps.sh

COLORS="$HOME/.local/state/omarchy/current/theme/colors.toml"
[[ -f $COLORS ]] || exit 0

color() {
  sed -nE "s/^$1[[:space:]]*=[[:space:]]*\"(#[0-9a-fA-F]{6})\".*/\1/p" "$COLORS" | head -1 | tr 'A-F' 'a-f'
}

bg=$(color background)
bg_dark=$(color dark_background)
bg_darker=$(color darker_background)
bg_light=$(color lighter_background)
fg=$(color foreground)
fg_dark=$(color dark_foreground)
fg_bright=$(color bright_foreground)
accent=$(color accent)
selection=$(color selection)
muted=$(color muted)
red=$(color red)
yellow=$(color yellow)
orange=$(color orange)
green=$(color green)
cyan=$(color cyan)
blue=$(color blue)
magenta=$(color magenta)

# Older themes may lack the extended keys
: "${bg_dark:=$bg}" "${bg_darker:=$bg_dark}" "${bg_light:=$selection}"
: "${fg_dark:=$muted}" "${fg_bright:=$fg}" "${accent:=$blue}" "${orange:=$yellow}"
[[ -n $bg && -n $fg ]] || exit 0

mode=$(sed -nE 's/^mode[[:space:]]*=[[:space:]]*"(.*)".*/\1/p' "$COLORS")
[[ $mode == light ]] && dark=false || dark=true

# ---------------------------------------------------------------- Zen Browser
theme_zen() {
  local profile chrome

  for profile in "$HOME"/.config/zen/*/ "$HOME"/.zen/*/; do
    [[ -f $profile/prefs.js ]] || continue
    chrome="$profile/chrome"
    mkdir -p "$chrome"

    cat >"$chrome/omarchy.css" <<EOF
/* Generated by the Omarchy theme-set hook. Do not edit. */
:root {
  --zen-colors-primary: $bg_light !important;
  --zen-primary-color: $accent !important;
  --zen-colors-secondary: $bg_light !important;
  --zen-colors-tertiary: $bg_dark !important;
  --zen-colors-border: $bg_light !important;
  --zen-colors-hover-bg: $bg_light !important;
  --zen-main-browser-background: $bg_darker !important;
  --zen-main-browser-background-toolbar: $bg_darker !important;
  --zen-themed-toolbar-bg: $bg_darker !important;
  --zen-themed-toolbar-bg-transparent: $bg_darker !important;
  --zen-dialog-background: $bg !important;
  --zen-urlbar-background: $bg_light !important;
  --toolbar-bgcolor: $bg_darker !important;
  --toolbar-color: $fg !important;
  --toolbar-field-background-color: $bg_light !important;
  --toolbar-field-focus-background-color: $bg_light !important;
  --toolbar-field-color: $fg !important;
  --toolbar-field-focus-color: $fg_bright !important;
  --toolbarbutton-icon-fill: $fg !important;
  --tab-selected-bgcolor: $bg_light !important;
  --tab-selected-textcolor: $fg_bright !important;
  --tab-hover-background-color: $bg !important;
  --lwt-text-color: $fg !important;
  --lwt-sidebar-background-color: $bg_darker !important;
  --lwt-sidebar-text-color: $fg !important;
  --sidebar-background-color: $bg_darker !important;
  --sidebar-text-color: $fg !important;
  --arrowpanel-background: $bg !important;
  --arrowpanel-color: $fg !important;
  --arrowpanel-border-color: $bg_light !important;
  --panel-separator-color: $bg_light !important;
  --urlbarView-highlight-background: $selection !important;
  --urlbarView-highlight-color: $fg_bright !important;
  --urlbar-box-bgcolor: $bg_light !important;
  --focus-outline-color: $accent !important;
  --button-primary-bgcolor: $accent !important;
  --button-primary-color: $bg_darker !important;
  --color-accent-primary: $accent !important;
}

#navigator-toolbox, #zen-main-app-wrapper, #browser, #titlebar, #TabsToolbar,
#zen-sidebar-top-buttons, #zen-sidebar-foot-buttons {
  background: $bg_darker !important;
  color: $fg !important;
}

::selection {
  background-color: $selection !important;
  color: $fg_bright !important;
}
EOF

    cat >"$chrome/omarchy-content.css" <<EOF
/* Generated by the Omarchy theme-set hook. Do not edit. */
@-moz-document url-prefix("about:") {
  :root {
    --in-content-page-background: $bg !important;
    --in-content-page-color: $fg !important;
    --in-content-box-background: $bg_dark !important;
    --in-content-box-border-color: $bg_light !important;
    --in-content-primary-button-background: $accent !important;
    --in-content-primary-button-text-color: $bg_darker !important;
    --background-color-box: $bg_dark !important;
    --background-color-canvas: $bg !important;
    --text-color: $fg !important;
    --color-accent-primary: $accent !important;
    --newtab-background-color: $bg !important;
    --newtab-background-color-secondary: $bg_light !important;
    --newtab-text-primary-color: $fg !important;
  }
}
EOF

    # Pull the generated files into userChrome/userContent without clobbering
    # anything the user already has there.
    ensure_import "$chrome/userChrome.css" omarchy.css
    ensure_import "$chrome/userContent.css" omarchy-content.css

    # user.js is re-applied on every Zen start
    set_pref "$profile/user.js" toolkit.legacyUserProfileCustomizations.stylesheets true
    set_pref "$profile/user.js" zen.theme.accent-color "\"$accent\""
    set_pref "$profile/user.js" layout.css.prefers-color-scheme.content-override "$([[ $dark == true ]] && echo 0 || echo 1)"
    set_pref "$profile/user.js" browser.theme.content-theme "$([[ $dark == true ]] && echo 0 || echo 1)"
    set_pref "$profile/user.js" browser.theme.toolbar-theme "$([[ $dark == true ]] && echo 0 || echo 1)"
  done
}

ensure_import() {
  local file="$1" target="$2"
  local line="@import url(\"$target\");"

  [[ -f $file ]] && grep -qF "$line" "$file" && return
  # @import must come before any other rule
  {
    echo "$line"
    if [[ -f $file ]]; then cat "$file"; fi
  } >"$file.tmp" && mv "$file.tmp" "$file"
}

set_pref() {
  local file="$1" key="$2" value="$3"

  touch "$file"
  sed -i "/user_pref(\"${key//./\\.}\",/d" "$file"
  echo "user_pref(\"$key\", $value);" >>"$file"
}

# -------------------------------------------------------------- IntelliJ IDEA
theme_intellij() {
  local config plugins build plugin_dir

  build=$(mktemp -d)

  mkdir -p "$build/META-INF"
  cat >"$build/META-INF/plugin.xml" <<EOF
<idea-plugin>
  <id>omarchy.theme</id>
  <name>Omarchy Theme</name>
  <version>1.0</version>
  <vendor>Omarchy</vendor>
  <description>Follows the current Omarchy theme. Generated by an Omarchy theme-set hook.</description>
  <idea-version since-build="223"/>
  <depends>com.intellij.modules.platform</depends>
  <extensions defaultExtensionNs="com.intellij">
    <themeProvider id="omarchy-theme" path="/omarchy.theme.json"/>
  </extensions>
</idea-plugin>
EOF

  cat >"$build/omarchy.theme.json" <<EOF
{
  "name": "Omarchy",
  "dark": $dark,
  "author": "Omarchy",
  "editorScheme": "/omarchy.xml",
  "ui": {
    "*": {
      "background": "$bg",
      "foreground": "$fg",
      "infoForeground": "$fg_dark",
      "disabledForeground": "$muted",
      "selectionBackground": "$selection",
      "selectionForeground": "$fg_bright",
      "selectionInactiveBackground": "$bg_light",
      "selectionBackgroundInactive": "$bg_light",
      "hoverBackground": "$bg_light",
      "borderColor": "$bg_light",
      "separatorColor": "$bg_light",
      "focusColor": "$accent",
      "focusedBorderColor": "$accent",
      "inactiveBackground": "$bg_dark",
      "underlinedTabBackground": "$bg_light",
      "underlineColor": "$accent"
    },
    "MainWindow.background": "$bg_darker",
    "MainToolbar.background": "$bg_darker",
    "MainToolbar.inactiveBackground": "$bg_darker",
    "Island.borderColor": "$bg_darker",
    "ToolWindow.background": "$bg",
    "ToolWindow.Header.background": "$bg",
    "ToolWindow.Header.inactiveBackground": "$bg",
    "ToolWindow.Stripe.background": "$bg_darker",
    "ToolWindow.Button.selectedBackground": "$bg_light",
    "StatusBar.background": "$bg_darker",
    "StatusBar.borderColor": "$bg_darker",
    "EditorTabs.background": "$bg",
    "EditorTabs.underlinedTabBackground": "$bg_light",
    "EditorTabs.underlineColor": "$accent",
    "EditorTabs.inactiveUnderlineColor": "$muted",
    "Editor.background": "$bg",
    "Tree.background": "$bg",
    "List.background": "$bg",
    "Table.background": "$bg",
    "Panel.background": "$bg",
    "Popup.background": "$bg_dark",
    "PopupMenu.background": "$bg_dark",
    "Menu.background": "$bg_dark",
    "ToolTip.background": "$bg_light",
    "TextField.background": "$bg_dark",
    "ComboBox.background": "$bg_dark",
    "ComboBox.nonEditableBackground": "$bg_dark",
    "Button.background": "$bg_light",
    "Button.default.startBackground": "$accent",
    "Button.default.endBackground": "$accent",
    "Button.default.foreground": "$bg_darker",
    "Link.activeForeground": "$accent",
    "Component.focusColor": "$accent",
    "ProgressBar.progressColor": "$accent",
    "ScrollBar.Mac.thumbColor": "${muted}80",
    "ScrollBar.thumbColor": "${muted}80"
  }
}
EOF

  local b=${bg#\#} bd=${bg_dark#\#} bl=${bg_light#\#} f=${fg#\#} fd=${fg_dark#\#}
  local s=${selection#\#} m=${muted#\#} a=${accent#\#}
  local r=${red#\#} y=${yellow#\#} o=${orange#\#} g=${green#\#} c=${cyan#\#} bu=${blue#\#} mg=${magenta#\#}
  local parent=$([[ $dark == true ]] && echo Darcula || echo Default)

  attr() { echo "    <option name=\"$1\"><value><option name=\"FOREGROUND\" value=\"$2\" />${3:+<option name=\"FONT_TYPE\" value=\"$3\" />}</value></option>"; }

  {
    cat <<EOF
<scheme name="Omarchy" version="142" parent_scheme="$parent">
  <colors>
    <option name="CARET_COLOR" value="$a" />
    <option name="CARET_ROW_COLOR" value="$bd" />
    <option name="GUTTER_BACKGROUND" value="$b" />
    <option name="LINE_NUMBERS_COLOR" value="$m" />
    <option name="LINE_NUMBER_ON_CARET_ROW_COLOR" value="$f" />
    <option name="SELECTION_BACKGROUND" value="$s" />
    <option name="CONSOLE_BACKGROUND_KEY" value="$b" />
    <option name="INDENT_GUIDE" value="$bl" />
    <option name="SELECTED_INDENT_GUIDE" value="$m" />
    <option name="RIGHT_MARGIN_COLOR" value="$bl" />
    <option name="TEARLINE_COLOR" value="$bl" />
    <option name="WHITESPACES" value="$bl" />
    <option name="DOCUMENTATION_COLOR" value="$bd" />
  </colors>
  <attributes>
    <option name="TEXT"><value><option name="FOREGROUND" value="$f" /><option name="BACKGROUND" value="$b" /></value></option>
EOF
    attr DEFAULT_KEYWORD "$mg"
    attr DEFAULT_STRING "$g"
    attr DEFAULT_VALID_STRING_ESCAPE "$c"
    attr DEFAULT_NUMBER "$o"
    attr DEFAULT_CONSTANT "$o"
    attr DEFAULT_LINE_COMMENT "$m" 2
    attr DEFAULT_BLOCK_COMMENT "$m" 2
    attr DEFAULT_DOC_COMMENT "$m" 2
    attr DEFAULT_DOC_COMMENT_TAG "$fd"
    attr DEFAULT_FUNCTION_DECLARATION "$bu"
    attr DEFAULT_FUNCTION_CALL "$bu"
    attr DEFAULT_CLASS_NAME "$y"
    attr DEFAULT_INTERFACE_NAME "$y"
    attr DEFAULT_INSTANCE_FIELD "$c"
    attr DEFAULT_STATIC_FIELD "$c"
    attr DEFAULT_INSTANCE_METHOD "$bu"
    attr DEFAULT_STATIC_METHOD "$bu"
    attr DEFAULT_PARAMETER "$r"
    attr DEFAULT_LOCAL_VARIABLE "$f"
    attr DEFAULT_IDENTIFIER "$f"
    attr DEFAULT_OPERATION_SIGN "$c"
    attr DEFAULT_BRACES "$fd"
    attr DEFAULT_BRACKETS "$fd"
    attr DEFAULT_PARENTHS "$fd"
    attr DEFAULT_COMMA "$fd"
    attr DEFAULT_SEMICOLON "$fd"
    attr DEFAULT_DOT "$fd"
    attr DEFAULT_METADATA "$y"
    attr DEFAULT_PREDEFINED_SYMBOL "$c"
    attr DEFAULT_TAG "$bu"
    attr DEFAULT_ATTRIBUTE "$y"
    attr DEFAULT_ENTITY "$o"
    attr ANNOTATION_NAME_ATTRIBUTES "$y"
    attr CONSOLE_NORMAL_OUTPUT "$f"
    attr CONSOLE_ERROR_OUTPUT "$r"
    attr CONSOLE_BLACK_OUTPUT "$bl"
    attr CONSOLE_RED_OUTPUT "$r"
    attr CONSOLE_GREEN_OUTPUT "$g"
    attr CONSOLE_YELLOW_OUTPUT "$y"
    attr CONSOLE_BLUE_OUTPUT "$bu"
    attr CONSOLE_MAGENTA_OUTPUT "$mg"
    attr CONSOLE_CYAN_OUTPUT "$c"
    attr CONSOLE_GRAY_OUTPUT "$fd"
    attr CONSOLE_WHITE_OUTPUT "$f"
    cat <<EOF
  </attributes>
</scheme>
EOF
  } >"$build/omarchy.xml"

  for plugins in "$HOME"/.local/share/JetBrains/*20*/; do
    plugin_dir="$plugins/omarchy-theme/lib"
    mkdir -p "$plugin_dir"
    rm -f "$plugin_dir/omarchy-theme.jar"
    (cd "$build" && zip -qr "$plugin_dir/omarchy-theme.jar" META-INF omarchy.theme.json omarchy.xml)
  done
  rm -rf "$build"

  # Select the theme and its editor scheme (picked up on next IDE start)
  for config in "$HOME"/.config/JetBrains/*20*/; do
    mkdir -p "$config/options"
    cat >"$config/options/laf.xml" <<EOF
<application>
  <component name="LafManager" autodetect="false">
    <laf themeId="omarchy-theme" />
  </component>
</application>
EOF
    cat >"$config/options/colors.scheme.xml" <<EOF
<application>
  <component name="EditorColorsManagerImpl">
    <global_color_scheme name="Omarchy" />
  </component>
</application>
EOF
  done
}

[[ -d $HOME/.config/zen || -d $HOME/.zen ]] && theme_zen
compgen -G "$HOME/.config/JetBrains/*20*/" >/dev/null && theme_intellij

exit 0
